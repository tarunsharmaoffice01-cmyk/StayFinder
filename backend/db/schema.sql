CREATE TABLE IF NOT EXISTS users (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  password TEXT NOT NULL,
  phone TEXT,
  avatar TEXT,
  role TEXT NOT NULL DEFAULT 'traveler'
    CHECK (role IN ('traveler', 'host', 'admin')),
  member_since TEXT,
  location TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS categories (
  id TEXT PRIMARY KEY,
  label TEXT NOT NULL,
  icon TEXT
);

CREATE TABLE IF NOT EXISTS destinations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  country TEXT NOT NULL,
  image TEXT,
  tag TEXT,
  properties_count INTEGER NOT NULL DEFAULT 0
    CHECK (properties_count >= 0)
);

CREATE TABLE IF NOT EXISTS properties (
  id TEXT PRIMARY KEY,
  title TEXT NOT NULL,
  location TEXT NOT NULL,
  country TEXT NOT NULL,
  price NUMERIC(10, 2) NOT NULL CHECK (price >= 0),
  rating NUMERIC(3, 2) NOT NULL DEFAULT 0
    CHECK (rating >= 0 AND rating <= 5),
  reviews INTEGER NOT NULL DEFAULT 0 CHECK (reviews >= 0),
  property_type TEXT NOT NULL,
  category TEXT NOT NULL,
  is_superhost BOOLEAN NOT NULL DEFAULT FALSE,
  guests INTEGER NOT NULL CHECK (guests > 0),
  bedrooms NUMERIC(4, 1) NOT NULL DEFAULT 1 CHECK (bedrooms >= 0),
  beds NUMERIC(4, 1) NOT NULL DEFAULT 1 CHECK (beds >= 0),
  bathrooms NUMERIC(4, 1) NOT NULL DEFAULT 1 CHECK (bathrooms >= 0),
  cleaning_fee NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (cleaning_fee >= 0),
  description TEXT NOT NULL,
  images TEXT[] NOT NULL DEFAULT '{}',
  amenities TEXT[] NOT NULL DEFAULT '{}',
  host_user_id TEXT REFERENCES users(id) ON DELETE SET NULL,
  host_name TEXT NOT NULL,
  host_image TEXT,
  host_response_rate TEXT,
  host_duration TEXT,
  house_rules TEXT[] NOT NULL DEFAULT '{}',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS properties_category_idx ON properties(category);
CREATE INDEX IF NOT EXISTS properties_host_user_id_idx ON properties(host_user_id);

CREATE TABLE IF NOT EXISTS bookings (
  id TEXT PRIMARY KEY,
  user_id TEXT REFERENCES users(id) ON DELETE SET NULL,
  property_id TEXT REFERENCES properties(id) ON DELETE SET NULL,
  property_title TEXT NOT NULL,
  property_location TEXT NOT NULL,
  property_image TEXT,
  property_type TEXT,
  check_in DATE NOT NULL,
  check_out DATE NOT NULL,
  nights INTEGER NOT NULL CHECK (nights > 0),
  guests INTEGER NOT NULL CHECK (guests > 0),
  price_per_night NUMERIC(10, 2) NOT NULL CHECK (price_per_night >= 0),
  subtotal NUMERIC(10, 2) NOT NULL CHECK (subtotal >= 0),
  cleaning_fee NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (cleaning_fee >= 0),
  service_fee NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (service_fee >= 0),
  occupancy_taxes NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (occupancy_taxes >= 0),
  total NUMERIC(10, 2) NOT NULL CHECK (total >= 0),
  status TEXT NOT NULL DEFAULT 'Confirmed'
    CHECK (status IN ('Pending', 'Confirmed', 'Cancelled', 'Completed')),
  guest_name TEXT NOT NULL,
  guest_email TEXT NOT NULL,
  host_name TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ,
  cancelled_at TIMESTAMPTZ,
  CHECK (check_out > check_in)
);

CREATE INDEX IF NOT EXISTS bookings_user_id_created_at_idx
  ON bookings(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS bookings_property_id_dates_idx
  ON bookings(property_id, check_in, check_out);

CREATE TABLE IF NOT EXISTS reviews (
  id TEXT PRIMARY KEY,
  property_id TEXT NOT NULL REFERENCES properties(id) ON DELETE CASCADE,
  user_id TEXT REFERENCES users(id) ON DELETE SET NULL,
  author TEXT NOT NULL,
  avatar TEXT,
  date TEXT,
  rating NUMERIC(2, 1) NOT NULL CHECK (rating >= 1 AND rating <= 5),
  text TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS reviews_property_id_created_at_idx
  ON reviews(property_id, created_at DESC);

CREATE TABLE IF NOT EXISTS wishlist_items (
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  property_id TEXT NOT NULL REFERENCES properties(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (user_id, property_id)
);

ALTER TABLE properties
  ADD COLUMN IF NOT EXISTS images TEXT[] NOT NULL DEFAULT '{}',
  ADD COLUMN IF NOT EXISTS amenities TEXT[] NOT NULL DEFAULT '{}';
